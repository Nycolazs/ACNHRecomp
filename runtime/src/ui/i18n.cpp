// The launcher's texts (launcher/): kLauncherEn, kLauncherPtBr, ...
#include "i18n_launcher.inc"

// clang-format on

struct Language {
    UiLanguage info;
    const Entry* entries;
    size_t count;
    const Entry* launcher;
    size_t launcher_count;
};

template <size_t N, size_t M>
constexpr Language lang(const char* code, const char* name, const Entry (&entries)[N], const Entry (&launcher)[M]) {
    return {{code, name}, entries, N, launcher, M};
}

// Display order; index 0 is the fallback (English).
const Language kLanguages[] = {
    lang("en", "English", kEn, kLauncherEn),
    lang("pt-BR", "Português (Brasil)", kPtBr, kLauncherPtBr),
    lang("es", "Español", kEs, kLauncherEs),
    lang("fr", "Français", kFr, kLauncherFr),
    lang("de", "Deutsch", kDe, kLauncherDe),
    lang("it", "Italiano", kIt, kLauncherIt),
    lang("nl", "Nederlands", kNl, kLauncherNl),
    lang("ru", "Русский", kRu, kLauncherRu),
    lang("ja", "日本語", kJa, kLauncherJa),
    lang("ko", "한국어", kKo, kLauncherKo),
    lang("zh-CN", "简体中文", kZhCn, kLauncherZhCn),
    lang("zh-TW", "繁體中文", kZhTw, kLauncherZhTw),
};
constexpr size_t kLanguageCount = sizeof(kLanguages) / sizeof(kLanguages[0]);

// key -> its text in every language (nullptr where a table lacks it). Built on first use and never written after,
// so concurrent tr() calls only read it; the function-local static makes the one-time build itself thread safe.
using Texts = std::array<const char*, kLanguageCount>;
const std::unordered_map<std::string_view, Texts>& index() {
    static const std::unordered_map<std::string_view, Texts> map = [] {
        std::unordered_map<std::string_view, Texts> m;
        m.reserve(kLanguages[0].count + kLanguages[0].launcher_count);
        for (size_t l = 0; l < kLanguageCount; l++) {
            for (size_t i = 0; i < kLanguages[l].count; i++) {
                const Entry& e = kLanguages[l].entries[i];
                m.try_emplace(e.key).first->second[l] = e.text;  // try_emplace value-initializes: all nullptr
            }
            for (size_t i = 0; i < kLanguages[l].launcher_count; i++) {
                const Entry& e = kLanguages[l].launcher[i];
                m.try_emplace(e.key).first->second[l] = e.text;
            }
        }
        return m;
    }();
    return map;
}

// An int, not the code string: tr() can run on another thread while the menu switches language.
std::atomic<size_t> g_current{0};

std::string lower(std::string_view s) {
    std::string r(s);
    for (char& c : r) c = char(std::tolower(static_cast<unsigned char>(c)));
    return r;
}

int find_code(std::string_view code) {
    for (size_t l = 0; l < kLanguageCount; l++)
        if (lower(kLanguages[l].info.code) == code) return int(l);
    return -1;
}

// A locale tag in any of the shapes the OSes use -- "pt_BR.UTF-8", "zh-Hant-TW", "sr_RS@latin", "en" -- to the index
// of the offered language it means, or -1. Only Brazilian Portuguese is offered, so any "pt" takes it; Chinese goes by
// script when the tag names one (Hans wins over a Hong Kong region), else by region.
int match_tag(std::string_view tag) {
    tag = tag.substr(0, tag.find_first_of(".@"));  // drop the encoding and the modifier
    std::string lang, script, region;
    size_t part = 0;
    while (!tag.empty()) {
        size_t cut = tag.find_first_of("-_");
        std::string sub = lower(tag.substr(0, cut));
        tag = cut == std::string_view::npos ? std::string_view() : tag.substr(cut + 1);
        if (part++ == 0)
            lang = sub;
        else if (sub.size() == 4 && script.empty() && region.empty())
            script = sub;
        else if ((sub.size() == 2 || sub.size() == 3) && region.empty())
            region = sub;
    }
    if (lang.empty() || lang == "c" || lang == "posix") return -1;
    if (lang == "pt") return find_code("pt-br");
    if (lang == "zh") {
        bool traditional = script == "hant" ||
                           (script != "hans" && (region == "tw" || region == "hk" || region == "mo"));
        return find_code(traditional ? "zh-tw" : "zh-cn");
    }
    if (lang.size() != 2) return -1;
    return find_code(lang);  // the regional entries ("pt-br", "zh-cn", "zh-tw") never equal a two-letter code
}

#if defined(NX_HAVE_SDL3)
int detect_sdl() {
    int count = 0;
    SDL_Locale** locales = SDL_GetPreferredLocales(&count);
    if (!locales) return -1;
    int found = -1;
    for (int i = 0; i < count && locales[i] && found < 0; i++) {
        std::string tag = locales[i]->language ? locales[i]->language : "";
        if (locales[i]->country) tag += std::string("_") + locales[i]->country;
        found = match_tag(tag);
    }
    SDL_free(locales);
    return found;
}
#endif

// Without SDL (or when SDL knows nothing): Windows' user locale, then the POSIX variables. LANGUAGE is GNU's ordered
// preference list ("pt_BR:en") and is what desktop language settings write, so it goes first; then LC_ALL, LC_MESSAGES
// and LANG in the precedence POSIX gives them for message texts.
int detect_os() {
#if defined(_WIN32)
    wchar_t wname[LOCALE_NAME_MAX_LENGTH] = {0};
    if (GetUserDefaultLocaleName(wname, LOCALE_NAME_MAX_LENGTH) > 0) {
        std::string name;
        for (const wchar_t* p = wname; *p; p++) name += char(*p < 0x80 ? *p : '?');  // locale names are ASCII
        if (int l = match_tag(name); l >= 0) return l;
    }
#endif
    if (const char* list = std::getenv("LANGUAGE")) {
        std::string_view rest = list;
        while (!rest.empty()) {
            size_t cut = rest.find(':');
            if (int l = match_tag(rest.substr(0, cut)); l >= 0) return l;
            rest = cut == std::string_view::npos ? std::string_view() : rest.substr(cut + 1);
        }
    }
    for (const char* var : {"LC_ALL", "LC_MESSAGES", "LANG"}) {
        const char* v = std::getenv(var);
        if (v && *v) return match_tag(v);  // the first one set decides, as in setlocale(); a non-match means English
    }
    return -1;
}

