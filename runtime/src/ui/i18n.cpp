const std::vector<UiLanguage>& ui_languages() {
    static const std::vector<UiLanguage> list = [] {
        std::vector<UiLanguage> v;
        for (const Language& l : kLanguages) v.push_back(l.info);
        return v;
    }();
    return list;
}

std::string ui_detect_system_language() {
    int l = -1;
#if defined(NX_HAVE_SDL3)
    l = detect_sdl();
#endif
    if (l < 0) l = detect_os();
    return kLanguages[l < 0 ? 0 : l].info.code;
}

void ui_set_language(const std::string& code) {
    std::string c = lower(code);
    int l = c.empty() || c == "auto" ? find_code(lower(ui_detect_system_language())) : find_code(c);
    if (l < 0) l = match_tag(code);  // "pt", "zh_Hant", "fr_CA": the closest offered language
    g_current.store(l < 0 ? 0 : size_t(l), std::memory_order_relaxed);
}

const std::string& ui_language() {
    // One string per language, made once, so the reference stays valid when the language changes.
    static const std::array<std::string, kLanguageCount> codes = [] {
        std::array<std::string, kLanguageCount> a;
        for (size_t l = 0; l < kLanguageCount; l++) a[l] = kLanguages[l].info.code;
        return a;
    }();
    return codes[g_current.load(std::memory_order_relaxed)];
}

const char* tr(const char* key) {
    if (!key) return "";
    const auto& map = index();
    auto it = map.find(key);
    if (it == map.end()) return key;
    const char* text = it->second[g_current.load(std::memory_order_relaxed)];
    if (text && *text) return text;
    text = it->second[0];
    return text && *text ? text : key;
}

std::string trf(const char* key, const std::string& arg) {
    std::string s = tr(key);
    size_t at = s.find("{}");
    if (at != std::string::npos) s.replace(at, 2, arg);
    return s;
}

