#!/usr/bin/env python3
"""Builds the ICC profile the F12 screenshots embed (runtime/src/nvn/nvn_pq_icc.inc): BT.2020 primaries, a PQ
signal, and a cicp tag (9, 16, 0, full) that Chrome reads (Chromium issue 40239687). Discord turns an upload into an
8-bit WebP preview: the PNG's own cICP chunk is lost there, the ICC is kept, so the preview shows in HDR too. Decoders
that ignore the cicp tag get the ICC's own curves: PQ to nits, 203 nits as white, clipped above (an SDR fallback).

usage: tools/shaders/hdr/make_pq_icc.py runtime/src/nvn/nvn_pq_icc.inc
"""
import struct, sys


def s15(x):  # s15Fixed16Number
    return struct.pack(">i", int(round(x * 65536)))


def mat_mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def mat_inv(m):
    (a, b, c), (d, e, f), (g, h, i) = m
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    return [[(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
            [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
            [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det]]


# BT.2020 RGB to XYZ (D65), and Bradford from D65 to the ICC's D50.
BT2020 = [[0.636958, 0.144617, 0.168881], [0.262700, 0.677998, 0.059302], [0.000000, 0.028073, 1.060985]]
BRADFORD = [[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]]
D65, D50 = (0.95047, 1.0, 1.08883), (0.96422, 1.0, 0.82521)
cone65 = [sum(BRADFORD[i][k] * D65[k] for k in range(3)) for i in range(3)]
cone50 = [sum(BRADFORD[i][k] * D50[k] for k in range(3)) for i in range(3)]
scale = [[cone50[i] / cone65[i] if i == j else 0.0 for j in range(3)] for i in range(3)]
CHAD = mat_mul(mat_inv(BRADFORD), mat_mul(scale, BRADFORD))
RGB_D50 = mat_mul(CHAD, BT2020)  # its columns: the colorants


def pq_nits(v):  # ST 2084 EOTF
    m1, m2, c1, c2, c3 = 2610 / 16384, 2523 / 32, 3424 / 4096, 2413 / 128, 2392 / 128
    e = v ** (1 / m2)
    return 10000 * (max(e - c1, 0) / (c2 - c3 * e)) ** (1 / m1)


def tag_xyz(x, y, z):
    return b"XYZ " + b"\0" * 4 + s15(x) + s15(y) + s15(z)


def tag_mluc(text):
    s = text.encode("utf-16-be")
    return b"mluc" + b"\0" * 4 + struct.pack(">II", 1, 12) + b"enUS" + struct.pack(">II", len(s), 28) + s


def tag_curv():  # the fallback: PQ to nits, 203 nits = 1, clipped
    n = 1024
    pts = [min(pq_nits(k / (n - 1)) / 203.0, 1.0) for k in range(n)]
    return b"curv" + b"\0" * 4 + struct.pack(">I", n) + b"".join(struct.pack(">H", round(p * 65535)) for p in pts)


def tag_sf32(m):
    return b"sf32" + b"\0" * 4 + b"".join(s15(m[i][j]) for i in range(3) for j in range(3))


trc = tag_curv()
tags = [
    (b"desc", tag_mluc("BT.2100 PQ (ACNHRecomp screenshot)")),
    (b"cprt", tag_mluc("No copyright, use freely")),
    (b"wtpt", tag_xyz(*D50)),
    (b"chad", tag_sf32(CHAD)),
    (b"rXYZ", tag_xyz(*[RGB_D50[i][0] for i in range(3)])),
    (b"gXYZ", tag_xyz(*[RGB_D50[i][1] for i in range(3)])),
    (b"bXYZ", tag_xyz(*[RGB_D50[i][2] for i in range(3)])),
    (b"rTRC", trc), (b"gTRC", trc), (b"bTRC", trc),
    (b"cicp", b"cicp" + b"\0" * 4 + bytes([9, 16, 0, 1])),  # BT.2020, PQ, RGB, full range
]
table = struct.pack(">I", len(tags))
body = b""
offset = 128 + 4 + 12 * len(tags)
data_at = {}
for sig, data in tags:
    if data in data_at:  # rTRC, gTRC, bTRC share one curve
        at = data_at[data]
    else:
        while (offset + len(body)) % 4:
            body += b"\0"
        at = offset + len(body)
        data_at[data] = at
        body += data
    table += sig + struct.pack(">II", at, len(data))
size = 128 + len(table) + len(body)
header = struct.pack(">I", size) + b"\0" * 4 + struct.pack(">I", 0x04400000) + b"mntrRGB XYZ "
header += struct.pack(">6H", 2026, 11, 1, 0, 0, 0) + b"acsp" + b"\0" * 4 + b"\0" * 4 + b"\0" * 8 + b"\0" * 8
header += struct.pack(">I", 0) + s15(D50[0]) + s15(D50[1]) + s15(D50[2]) + b"\0" * 4 + b"\0" * 16 + b"\0" * 28
assert len(header) == 128
icc = header + table + body
lines = ["// Generated by tools/shaders/hdr/make_pq_icc.py. Do not edit.\n",
         "// The BT.2100 PQ ICC profile (with a cicp tag) the F12 screenshots embed (nvn_screenshot.cpp).\n",
         "const uint8_t kPqIcc[] = {\n"]
for i in range(0, len(icc), 16):
    lines.append("    " + ", ".join("0x%02x" % b for b in icc[i:i + 16]) + ",\n")
lines.append("};\n")
open(sys.argv[1], "w").write("".join(lines))
print(f"{sys.argv[1]}: {len(icc)} bytes")
